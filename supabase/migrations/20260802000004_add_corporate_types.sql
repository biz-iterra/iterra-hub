-- ============================================================
-- 法人格マスタの補充と再適用
--
-- 20260802000003 で会社名から法人格を決められるようにしたが、
-- マスタが 6 種しか無く、実データの 125 件ほどが受け皿を持たなかった
-- （公益財団法人 62 / 協同組合 24 / 一般財団法人 15 など）。
--
-- `expand_corporate_abbreviations` が略記を開く法人格は、開いた先を
-- 受け止められるようマスタにも揃えておく。
--
-- 「有限責任事業組合」「労働組合」は入れない。前者は法人格を持たず、
-- 後者は取引先として扱う場面が無い。名称に「組合」を含むだけの任意団体を
-- 巻き込まないよう、組合は「協同組合」に限る
-- （事業協同組合・農業協同組合・漁業協同組合はいずれも部分一致で当たる）。
-- ============================================================

INSERT INTO corporate_types (name) VALUES
  ('合資会社'),
  ('合名会社'),
  ('一般財団法人'),
  ('公益社団法人'),
  ('公益財団法人'),
  ('特定非営利活動法人'),
  ('医療法人'),
  ('社会福祉法人'),
  ('学校法人'),
  ('宗教法人'),
  ('協同組合'),
  ('弁護士法人'),
  ('税理士法人'),
  ('司法書士法人'),
  ('行政書士法人'),
  ('社会保険労務士法人'),
  ('弁理士法人'),
  ('監査法人')
ON CONFLICT (name) DO NOTHING;

-- ------------------------------------------------------------
-- 増えた法人格を既存の会社へ当てる。
-- 人が選んだ値は上書きしない（空いているものだけ埋める）。
-- ------------------------------------------------------------
UPDATE companies
   SET corporate_type_id = resolve_corporate_type_id(name)
 WHERE corporate_type_id IS NULL
   AND resolve_corporate_type_id(name) IS NOT NULL;
