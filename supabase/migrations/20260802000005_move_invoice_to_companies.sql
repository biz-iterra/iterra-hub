-- ============================================================
-- インボイス登録番号は事業者（companies）を正本にする
--
-- 20260801000010 で連絡先から取引先へ移したが、`companies` にも同じ列があり
-- どちらが正本か決まっていなかった。適格請求書発行事業者の登録番号は
-- **事業者に付く番号**なので、事業者情報が持つ方が実態に合う。
--
-- 個人事業主も屋号で `companies` に登録する運用にしたため
-- （法人格「個人事業主」で区別する）、法人・個人事業主のどちらも
-- 事業者情報に番号を持ち、契約成立時に取引先へ昇格する流れで揃う。
--
-- 取引先の画面では紐づく事業者情報の番号を読み取りで見せる。
-- 実データは 0 件なので移送は不要。
-- ============================================================

ALTER TABLE accounts
  DROP COLUMN invoice_registered,
  DROP COLUMN invoice_registration_number;

COMMENT ON COLUMN companies.invoice_registration_number IS
  '適格請求書発行事業者の登録番号（T+13 桁）。事業者に付く番号なのでここが正本';
