-- deals.contract_name を非推奨にする（T-0063）
--
--   ディールの新規作成・編集フォームに「契約名」という入力欄があり、
--   `deals.contract_name`（ただのテキスト列）へ手入力させていた。
--   契約の実体は `contracts` にあり、`contracts.deal_id` でディールに紐づく。
--   同じものが 2 か所にあり、片方を直しても片方が古いまま残っていた。
--
--   2026-08-07 に画面と Zod スキーマから外し、契約は `contracts` へ一本化した。
--
-- **列は落とさない。** 既存の値は過去に人が入れた記録で、消すと戻せない。
--   `contracts` へ機械的に移すこともしない（契約レコードを勝手に作ることになり、
--   契約成立の判断をシステムが代行してしまう）。読むだけの死んだ列として残す。
--
--   落とすなら、値の残る行を人が確認して `contracts` へ起こしたあと。
-- ============================================================

